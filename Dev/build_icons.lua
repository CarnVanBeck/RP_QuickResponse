-- Builds IconData.lua: the names of the game's icons, so the icon browser can search them.
-- The game only hands addons file IDs (GetMacroIcons); the names come from the community
-- listfile (https://github.com/wowdev/wow-listfile, "verified-listfile-withcapitals.csv").
--
--   luajit Dev/build_icons.lua <listfile.csv> > IconData.lua
--
-- Output: one long string "fileID name\n..." that the browser parses the first time it opens,
-- so the list costs nothing at login.
local path = assert(arg[1], "usage: luajit Dev/build_icons.lua <listfile.csv>")

local entries = {}
for line in io.lines(path) do
    local id, name = line:match("^(%d+);[Ii][Nn][Tt][Ee][Rr][Ff][Aa][Cc][Ee]/[Ii][Cc][Oo][Nn][Ss]/([^/]+)%.[Bb][Ll][Pp]\r?$")
    if id then
        entries[#entries + 1] = { id = tonumber(id), name = name }
    end
end
table.sort(entries, function(a, b) return a.id < b.id end)

local out = {}
for _, entry in ipairs(entries) do
    out[#out + 1] = entry.id .. " " .. entry.name
end
local body = table.concat(out, "\n")
assert(not body:find("]==]", 1, true), "an icon name would end the long string")

io.write("-- Generated by Dev/build_icons.lua from the wow-listfile community listfile. Do not edit.\n")
io.write("-- ", #entries, " icons: \"fileID name\" per line.\n")
io.write("local _, ns = ...\n\n")
io.write("ns.ICON_NAMES = [==[\n", body, "\n]==]\n")
